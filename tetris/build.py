"""Build Tetris: generate the piece tables, assemble, and wrap in a .tap with a BASIC loader.

    python build.py                 -> build/tetris.tap and build/tetris.sna (the game)
    python build.py --test NAME     -> build/test_NAME.tap (scripted self-playing test build)

Run with the project's venv Python (it uses specbot.tape to write the tape).
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

from specbot.tape import code_tap, program_tap, tokenize_program  # noqa: E402

SJASMPLUS = HERE / "tools" / "sjasmplus-1.24.0.win" / "sjasmplus.exe"
SRC = HERE / "src"
BUILD = HERE / "build"
ORG = 32768

# Cells of each piece in each rotation, as (x, y) in a 4x4 box (SRS orientations).
PIECES = {
    "I": ["....####........", "..#...#...#...#.", "........####....", ".#...#...#...#.."],
    "O": [".##..##........."] * 4,
    "T": [".#..###.........", ".#...##..#......", "....###..#......", ".#..##...#......"],
    "S": [".##.##..........", ".#...##...#.....", ".....##.##......", "#...##...#......"],
    "Z": ["##...##.........", "..#..##..#......", "....##...##.....", ".#..##..#......."],
    "J": ["#...###.........", ".##..#...#......", "....###...#.....", ".#...#..##......"],
    "L": ["..#.###.........", ".#...#...##.....", "....###.#.......", "##...#...#......"],
}
ORDER = "IOTSZJL"

# Key bits, matching the K_ constants in tetris.asm.
KEYS = {"L": 1, "R": 2, "T": 4, "S": 8, "D": 16, "P": 32, "C": 64, ".": 0}


def piece_table() -> str:
    lines = ["; generated by build.py: (field offset = y*16+x, attribute offset = y*32+x) per cell", "pieces:"]
    for name in ORDER:
        for rot, shape in enumerate(PIECES[name]):
            cells = [(i % 4, i // 4) for i, ch in enumerate(shape) if ch == "#"]
            assert len(cells) == 4, (name, rot)
            data = ", ".join(f"{y * 16 + x}, {y * 32 + x}" for x, y in cells)
            lines.append(f"        db {data}        ; {name} rotation {rot}")
    return "\n".join(lines) + "\n"


def parse_script(text: str) -> list[tuple[int, int]]:
    """'L 5.' style script: each token is keys (letters) + frame count, e.g. 'L1 .3 D1 .40'."""
    steps = []
    for token in text.split():
        m = re.fullmatch(r"([LRTSDPC.]+)(\d+)", token)
        if not m:
            raise SystemExit(f"bad script token {token!r}")
        mask = 0
        for ch in m.group(1):
            mask |= KEYS[ch]
        frames = int(m.group(2))
        while frames > 0:
            steps.append((min(frames, 255), mask))
            frames -= 255
    return steps


def test_include(pieces: str, script: str) -> str:
    seq = ", ".join(str(ORDER.index(p)) for p in pieces)
    lines = [f"test_seq:\n        db {seq}", "test_script:"]
    for frames, mask in parse_script(script):
        lines.append(f"        db {frames}, {mask}")
    lines.append("        db 0")
    return "\n".join(lines) + "\n"


def symbols(path: Path) -> dict[str, int]:
    table = {}
    for line in path.read_text().splitlines():
        m = re.match(r"(\S+?):?\s+EQU\s+0x([0-9A-Fa-f]+)", line)
        if m:
            table[m.group(1)] = int(m.group(2), 16)
    return table


def build(name: str, test: tuple[str, str] | None = None) -> Path:
    BUILD.mkdir(exist_ok=True)
    (SRC / "pieces.inc").write_text(piece_table())
    args = [str(SJASMPLUS), "--nologo", "--msg=war", f"--raw={BUILD / (name + '.bin')}",
            f"--sym={BUILD / (name + '.sym')}", f"--lst={BUILD / (name + '.lst')}", f"-I{SRC}"]
    if test:
        (SRC / "test.inc").write_text(test_include(*test))
        args.append("-DTEST=1")
    args.append((SRC / "tetris.asm").as_posix())
    result = subprocess.run(args, capture_output=True, text=True)
    sys.stderr.write(result.stdout + result.stderr)
    if result.returncode:
        raise SystemExit("assembly failed")
    code = (BUILD / (name + ".bin")).read_bytes()
    sym = symbols(BUILD / (name + ".sym"))

    loader = [
        "10 CLEAR 32767: BORDER 0: PAPER 0: INK 0: CLS",
        '20 LOAD "" CODE',
        f"30 RANDOMIZE USR {ORG}",
    ]
    if test:
        # After the script ends the game returns here: show the frame counters and stop.
        def word(label: str) -> str:
            a = sym[label]
            return f"PEEK {a}+256*PEEK {a + 1}"

        loader.append(
            f'40 PRINT AT 0,0; INK 7; "h=";{word("halts")};" f=";'
            f'{word("t_end")}-({word("t_start")});"   "'
        )
        loader.append("50 STOP")
    tap = program_tap(tokenize_program("\n".join(loader)), "TETRIS", autostart=10)
    tap += code_tap(code, ORG, "tetris")
    out = BUILD / (name + ".tap")
    out.write_bytes(tap)
    print(f"{out.name}: {len(code)} bytes of code, {ORG}-{ORG + len(code) - 1}")
    if not test:
        # Also a 48K snapshot: the whole machine with the game about to start.
        snap = subprocess.run(
            [str(SJASMPLUS), "--nologo", "--msg=war", f"-I{SRC}", (SRC / "snapshot.asm").as_posix()],
            capture_output=True, text=True, cwd=BUILD,
        )
        sys.stderr.write(snap.stdout + snap.stderr)
        if snap.returncode:
            raise SystemExit("snapshot assembly failed")
        print(f"{name}.sna: {(BUILD / 'tetris.sna').stat().st_size} bytes")
    return out


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--test", metavar="NAME", help="build a scripted test (see tests.py)")
    args = parser.parse_args()
    if args.test:
        from tests import TESTS

        spec = TESTS[args.test]
        build("test_" + args.test, (spec["pieces"], spec["script"]))
    else:
        build("tetris")


if __name__ == "__main__":
    main()
